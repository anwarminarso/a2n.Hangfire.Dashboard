@cli.command()
def stats():
    """Count the stress jobs by state and stored fingerprint."""
    conn, provider = get_connection()
    try:
        cur = conn.cursor()
        state_col = "StateName" if provider == "sqlserver" else "statename"
        cur.execute(f"SELECT {state_col}, COUNT(*) FROM {_job_table(provider)} WHERE {_marker_where(provider)} GROUP BY {state_col}")
        rows = cur.fetchall()
        cur.close()
        for state, count in sorted(rows, key=lambda r: -r[1]):
            console.print(f"  {state or '—':<12} {count:>10,}")
        console.print(f"  stored fingerprints on failures: {stress_failure_count(conn, provider, True):,}")
    finally:
        conn.close()


