"""
bulkseed.py — set-based seeding for the volume tiers (100k – 1M jobs) and real failures.

`jobs.py seed` inserts one job at a time (four round trips each), fine for a few hundred jobs but
not for a million. Here each batch is generated by the database itself (generate_series on
PostgreSQL, a numbers CTE on SQL Server) in a handful of statements.

Every job seeded here invokes SampleApp.SharedJobs.StressJobs, so `purge` can remove exactly the
harness's rows and nothing else:

    volume    Succeeded / Deleted / Scheduled / Failed / Enqueued rows written directly, for list
              pages and Search. Enqueued ones go to the queue "hfload-idle", which no server
              listens to, so they stay put. The Failed ones carry synthetic exceptions and no
              stored FailureFingerprint.
    failures  Enqueued StressJobs.Fail(kind) jobs in a queue the SampleApp server processes. The
              worker fails them for real, so FailureFingerprintFilter stores the same fingerprint
              the dashboard computes, with no copy of its rules here. `wait` blocks until done.
    unstore   removes the stored FailureFingerprint of a share of those failures, for the
              "without stored fingerprints" and "mixed" grouping runs.

Usage:
    python cli.py bulk volume --total 100000 --yes
    python cli.py bulk failures --count 10000 --kinds 50 --wait --yes
    python cli.py bulk unstore --fraction 0.5 --yes
    python cli.py bulk purge --yes
"""
from __future__ import annotations

import json
import time

import click
from rich.console import Console
from rich.progress import BarColumn, Progress, TextColumn, TimeElapsedColumn

import config as cfg_mod
import guard
from db import get_connection

console = Console()

STRESS_TYPE = "SampleApp.SharedJobs.StressJobs, SampleApp.SharedJobs"
STRESS_MARKER = "SampleApp.SharedJobs.StressJobs"
IDLE_QUEUE = "hfload-idle"
FINGERPRINT_PARAMETER = "FailureFingerprint"
BATCH = 50_000

# Share of each state in a volume seed. Failed rows here are synthetic; real ones come from `failures`.
DEFAULT_MIX = {"Succeeded": 0.70, "Failed": 0.12, "Deleted": 0.10, "Scheduled": 0.05, "Enqueued": 0.03}

# Synthetic exceptions for volume-seeded Failed rows: (type, message), picked by row number.
_SYNTHETIC_FAILURES = [
    ("System.TimeoutException", "The volume seed gateway did not answer."),
    ("System.InvalidOperationException", "The volume seed record is locked."),
    ("System.ArgumentException", "The volume seed payload failed validation."),
    ("System.IO.IOException", "The volume seed export file is in use."),
    ("System.UnauthorizedAccessException", "The volume seed mailbox rejected the login."),
]


def _invocation(provider: str, method: str) -> str:
    """StressJobs.<method>(int) as each storage stores it; see jobs.invocation_data."""
    from jobs import JobSpec, invocation_data
    return invocation_data(provider, JobSpec(STRESS_TYPE, method, ("System.Int32",)))


# ─── PostgreSQL ───────────────────────────────────────────────────────────────

def _pg_state_data_sql(state: str) -> tuple[str, str | None]:
    """(SQL expression for state.data from row number g and createdat c, reason)."""
    # mod() rather than %, which psycopg would read as a placeholder. ::jsonb fits both a jsonb and
    # a text column (an assignment cast to text exists for every type; text to jsonb doesn't).
    ts = "to_char(c, 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"0Z\"')"
    if state == "Succeeded":
        return (f"json_build_object('SucceededAt', {ts}, 'PerformanceDuration', (mod(g, 5000) + 10)::text, "
                f"'Latency', (mod(g, 900) + 5)::text)::jsonb", "The job has been completed successfully.")
    if state == "Deleted":
        return f"json_build_object('DeletedAt', {ts})::jsonb", "Deleted by the load-test seed"
    if state == "Scheduled":
        return (f"json_build_object('EnqueueAt', to_char(c + interval '7 days', 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"0Z\"'), "
                f"'ScheduledAt', {ts})::jsonb", None)
    if state == "Enqueued":
        return f"json_build_object('EnqueuedAt', {ts}, 'Queue', '{IDLE_QUEUE}')::jsonb", None
    if state == "Failed":
        types = "ARRAY[" + ",".join(f"'{t}'" for t, _ in _SYNTHETIC_FAILURES) + "]"
        messages = "ARRAY[" + ",".join(f"'{m}'" for _, m in _SYNTHETIC_FAILURES) + "]"
        k = f"mod(g, {len(_SYNTHETIC_FAILURES)}) + 1"
        details = (f"({types})[{k}] || ': ' || ({messages})[{k}] || "
                   "E'\\n   at SampleApp.SharedJobs.StressJobs.Fail(Int32 kind)'")
        return (f"json_build_object('FailedAt', {ts}, 'ExceptionType', ({types})[{k}], "
                f"'ExceptionMessage', ({messages})[{k}], 'ExceptionDetails', {details})::jsonb",
                "An exception occurred during performance of the job.")
    raise ValueError(state)


def _pg_seed_batch(cur, state: str, count: int, spread_hours: float):
    method = "Fail" if state == "Failed" else "Succeed"
    data_sql, reason = _pg_state_data_sql(state)
    expire = "now() + interval '7 days'" if state in ("Succeeded", "Deleted") else "NULL"
    cur.execute("SET LOCAL TIME ZONE 'UTC'")
    cur.execute("CREATE TEMP TABLE IF NOT EXISTS hfload_new (id bigint, g bigint, c timestamptz) ON COMMIT DROP")
    cur.execute("TRUNCATE hfload_new")
    cur.execute(f"""
        WITH j AS (
            INSERT INTO hangfire.job (invocationdata, arguments, createdat, expireat, statename)
            SELECT %s::jsonb, ('["' || g || '"]')::jsonb,
                   now() - random() * (%s * interval '1 hour'), {expire}, %s
            FROM generate_series(1, %s) AS g
            RETURNING id, createdat
        )
        INSERT INTO hfload_new (id, g, c) SELECT id, id, createdat FROM j
    """, (_invocation("postgresql", method), spread_hours, state, count))
    cur.execute(f"""
        WITH s AS (
            INSERT INTO hangfire.state (jobid, name, reason, createdat, data)
            SELECT id, %s, %s, c, {data_sql} FROM hfload_new
            RETURNING id, jobid
        )
        UPDATE hangfire.job j SET stateid = s.id FROM s WHERE j.id = s.jobid
    """, (state, reason))
    if state == "Enqueued":
        cur.execute("INSERT INTO hangfire.jobqueue (jobid, queue) SELECT id, %s FROM hfload_new", (IDLE_QUEUE,))


def _pg_enqueue_failures(cur, count: int, kinds: int, fixed_kind: int | None, queue: str):
    cur.execute("SET LOCAL TIME ZONE 'UTC'")
    kind = str(int(fixed_kind)) if fixed_kind is not None else f"mod(g, {int(kinds)})"
    cur.execute("CREATE TEMP TABLE IF NOT EXISTS hfload_new (id bigint, g bigint, c timestamptz) ON COMMIT DROP")
    cur.execute("TRUNCATE hfload_new")
    cur.execute(f"""
        WITH j AS (
            INSERT INTO hangfire.job (invocationdata, arguments, createdat, statename)
            SELECT %s::jsonb, ('["' || {kind} || '"]')::jsonb, now(), 'Enqueued'
            FROM generate_series(1, %s) AS g
            RETURNING id, createdat
        )
        INSERT INTO hfload_new (id, g, c) SELECT id, id, createdat FROM j
    """, (_invocation("postgresql", "Fail"), count))
    ts = "to_char(c, 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"0Z\"')"
    cur.execute(f"""
        WITH s AS (
            INSERT INTO hangfire.state (jobid, name, reason, createdat, data)
            SELECT id, 'Enqueued', NULL, c, json_build_object('EnqueuedAt', {ts}, 'Queue', %s::text)::jsonb FROM hfload_new
            RETURNING id, jobid
        )
        UPDATE hangfire.job j SET stateid = s.id FROM s WHERE j.id = s.jobid
    """, (queue,))
    cur.execute("INSERT INTO hangfire.jobqueue (jobid, queue) SELECT id, %s FROM hfload_new", (queue,))


# ─── SQL Server ───────────────────────────────────────────────────────────────

_MSSQL_NUMBERS = """
WITH n AS (
    SELECT TOP (?) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS g
    FROM sys.all_objects a CROSS JOIN sys.all_objects b CROSS JOIN sys.all_objects c
)"""


def _mssql_ts(col: str) -> str:
    return f"CONVERT(varchar(30), {col}, 126) + 'Z'"


def _mssql_state_data_sql(state: str) -> tuple[str, str | None]:
    ts = _mssql_ts("c")
    if state == "Succeeded":
        return (f"CONCAT('{{\"SucceededAt\":\"', {ts}, '\",\"PerformanceDuration\":\"', g % 5000 + 10, "
                f"'\",\"Latency\":\"', g % 900 + 5, '\"}}')", "The job has been completed successfully.")
    if state == "Deleted":
        return f"CONCAT('{{\"DeletedAt\":\"', {ts}, '\"}}')", "Deleted by the load-test seed"
    if state == "Scheduled":
        return (f"CONCAT('{{\"EnqueueAt\":\"', {_mssql_ts('DATEADD(DAY, 7, c)')}, '\",\"ScheduledAt\":\"', {ts}, '\"}}')",
                None)
    if state == "Enqueued":
        return f"CONCAT('{{\"EnqueuedAt\":\"', {ts}, '\",\"Queue\":\"{IDLE_QUEUE}\"}}')", None
    if state == "Failed":
        cases_type = " ".join(f"WHEN {i} THEN '{t}'" for i, (t, _) in enumerate(_SYNTHETIC_FAILURES))
        cases_msg = " ".join(f"WHEN {i} THEN '{m}'" for i, (_, m) in enumerate(_SYNTHETIC_FAILURES))
        k = f"g % {len(_SYNTHETIC_FAILURES)}"
        t = f"(CASE {k} {cases_type} END)"
        m = f"(CASE {k} {cases_msg} END)"
        return (f"CONCAT('{{\"FailedAt\":\"', {ts}, '\",\"ExceptionType\":\"', {t}, '\",\"ExceptionMessage\":\"', {m}, "
                f"'\",\"ExceptionDetails\":\"', {t}, ': ', {m}, '\\n   at SampleApp.SharedJobs.StressJobs.Fail(Int32 kind)\"}}')",
                "An exception occurred during performance of the job.")
    raise ValueError(state)


def _mssql_seed_batch(cur, state: str, count: int, spread_hours: float):
    method = "Fail" if state == "Failed" else "Succeed"
    data_sql, reason = _mssql_state_data_sql(state)
    expire = "DATEADD(DAY, 7, SYSUTCDATETIME())" if state in ("Succeeded", "Deleted") else "NULL"
    spread_s = max(1, int(spread_hours * 3600))
    cur.execute(f"""
        SET NOCOUNT ON;
        CREATE TABLE #hfload_new (Id bigint, g bigint, c datetime);
        {_MSSQL_NUMBERS}
        INSERT INTO [HangFire].Job (InvocationData, Arguments, CreatedAt, ExpireAt, StateName)
        OUTPUT INSERTED.Id, INSERTED.Id, INSERTED.CreatedAt INTO #hfload_new (Id, g, c)
        SELECT ?, CONCAT('["', g, '"]'),
               DATEADD(SECOND, -(ABS(CHECKSUM(NEWID())) % {spread_s}), SYSUTCDATETIME()), {expire}, ?
        FROM n;
        CREATE TABLE #hfload_state (Id bigint, JobId bigint);
        INSERT INTO [HangFire].State (JobId, Name, Reason, CreatedAt, Data)
        OUTPUT INSERTED.Id, INSERTED.JobId INTO #hfload_state (Id, JobId)
        SELECT Id, ?, ?, c, {data_sql} FROM #hfload_new;
        UPDATE j SET StateId = s.Id FROM [HangFire].Job j JOIN #hfload_state s ON j.Id = s.JobId;
        {"INSERT INTO [HangFire].JobQueue (JobId, Queue) SELECT Id, ? FROM #hfload_new;" if state == "Enqueued" else ""}
        DROP TABLE #hfload_state;
        DROP TABLE #hfload_new;
    """, (count, _invocation("sqlserver", method), state, state, reason, *((IDLE_QUEUE,) if state == "Enqueued" else ())))


def _mssql_enqueue_failures(cur, count: int, kinds: int, fixed_kind: int | None, queue: str):
    kind = str(int(fixed_kind)) if fixed_kind is not None else f"g % {int(kinds)}"
    cur.execute(f"""
        SET NOCOUNT ON;
        CREATE TABLE #hfload_new (Id bigint, c datetime);
        {_MSSQL_NUMBERS}
        INSERT INTO [HangFire].Job (InvocationData, Arguments, CreatedAt, StateName)
        OUTPUT INSERTED.Id, INSERTED.CreatedAt INTO #hfload_new (Id, c)
        SELECT ?, CONCAT('["', {kind}, '"]'), SYSUTCDATETIME(), 'Enqueued' FROM n;
        CREATE TABLE #hfload_state (Id bigint, JobId bigint);
        INSERT INTO [HangFire].State (JobId, Name, Reason, CreatedAt, Data)
        OUTPUT INSERTED.Id, INSERTED.JobId INTO #hfload_state (Id, JobId)
        SELECT Id, 'Enqueued', NULL, c, CONCAT('{{"EnqueuedAt":"', {_mssql_ts('c')}, '","Queue":"', ?, '"}}') FROM #hfload_new;
        UPDATE j SET StateId = s.Id FROM [HangFire].Job j JOIN #hfload_state s ON j.Id = s.JobId;
        INSERT INTO [HangFire].JobQueue (JobId, Queue) SELECT Id, ? FROM #hfload_new;
        DROP TABLE #hfload_state;
        DROP TABLE #hfload_new;
    """, (count, _invocation("sqlserver", "Fail"), queue, queue))


# ─── shared ───────────────────────────────────────────────────────────────────

def _job_table(provider: str) -> str:
    return "[HangFire].Job" if provider == "sqlserver" else "hangfire.job"


def _marker_where(provider: str) -> str:
    # strpos / CHARINDEX rather than LIKE '%…%': psycopg would read the % signs as placeholders.
    if provider == "sqlserver":
        return f"CHARINDEX(N'{STRESS_MARKER}', InvocationData) > 0"
    return f"strpos(invocationdata::text, '{STRESS_MARKER}') > 0"


def seed_volume(conn, provider: str, total: int, mix: dict[str, float] | None = None,
                spread_hours: float = 48.0) -> dict[str, int]:
    """Seed `total` StressJobs rows across states; returns how many of each were written."""
    mix = mix or DEFAULT_MIX
    plan = {state: int(round(total * share)) for state, share in mix.items()}
    written = {state: 0 for state in plan}
    batch_fn = _mssql_seed_batch if provider == "sqlserver" else _pg_seed_batch

    with Progress(TextColumn("[cyan]{task.description}"), BarColumn(),
                  TextColumn("{task.completed:,}/{task.total:,}"), TimeElapsedColumn(), console=console) as progress:
        task = progress.add_task("Seeding volume", total=sum(plan.values()))
        for state, count in plan.items():
            remaining = count
            while remaining > 0:
                n = min(BATCH, remaining)
                cur = conn.cursor()
                try:
                    batch_fn(cur, state, n, spread_hours)
                    conn.commit()
                finally:
                    cur.close()
                remaining -= n
                written[state] += n
                progress.update(task, advance=n)
    return written


def enqueue_failures(conn, provider: str, count: int, kinds: int = 50, fixed_kind: int | None = None,
                     queue: str = "default") -> int:
    """Enqueue `count` StressJobs.Fail jobs for the SampleApp server to fail for real."""
    fn = _mssql_enqueue_failures if provider == "sqlserver" else _pg_enqueue_failures
    remaining = count
    while remaining > 0:
        n = min(BATCH, remaining)
        cur = conn.cursor()
        try:
            fn(cur, n, kinds, fixed_kind, queue)
            conn.commit()
        finally:
            cur.close()
        remaining -= n
    return count


def pending_stress_jobs(conn, provider: str) -> int:
    """StressJobs jobs still Enqueued in a served queue, or Processing."""
    cur = conn.cursor()
    try:
        if provider == "sqlserver":
            cur.execute(f"""
                SELECT COUNT(*) FROM [HangFire].Job j
                WHERE j.StateName IN ('Enqueued', 'Processing') AND {_marker_where(provider)}
                  AND NOT EXISTS (SELECT 1 FROM [HangFire].JobQueue q WHERE q.JobId = j.Id AND q.Queue = ?)
            """, (IDLE_QUEUE,))
        else:
            cur.execute(f"""
                SELECT COUNT(*) FROM hangfire.job j
                WHERE j.statename IN ('Enqueued', 'Processing') AND {_marker_where(provider)}
                  AND NOT EXISTS (SELECT 1 FROM hangfire.jobqueue q WHERE q.jobid = j.id AND q.queue = %s)
            """, (IDLE_QUEUE,))
        return int(cur.fetchone()[0])
    finally:
        cur.close()
        conn.commit()


def other_queued_jobs(conn, provider: str) -> int:
    """Non-StressJobs jobs waiting in any queue but the idle one. A server dequeues by job id, so
    older leftovers (e.g. from an earlier run that was stopped mid-way) are worked off first."""
    cur = conn.cursor()
    try:
        if provider == "sqlserver":
            cur.execute(f"""
                SELECT COUNT(*) FROM [HangFire].JobQueue q JOIN [HangFire].Job j ON j.Id = q.JobId
                WHERE q.Queue <> ? AND q.FetchedAt IS NULL AND NOT ({_marker_where(provider)})
            """, (IDLE_QUEUE,))
        else:
            cur.execute(f"""
                SELECT COUNT(*) FROM hangfire.jobqueue q JOIN hangfire.job j ON j.id = q.jobid
                WHERE q.queue <> %s AND q.fetchedat IS NULL AND NOT ({_marker_where(provider)})
            """, (IDLE_QUEUE,))
        return int(cur.fetchone()[0])
    finally:
        cur.close()
        conn.commit()


def wait_until_processed(conn, provider: str, timeout_s: float = 1800, poll_s: float = 5.0) -> tuple[bool, float]:
    """Block until no StressJobs job is waiting in a served queue; returns (done, seconds)."""
    started = time.monotonic()
    last = None
    last_other_report = 0.0
    while time.monotonic() - started < timeout_s:
        pending = pending_stress_jobs(conn, provider)
        if pending == 0:
            return True, time.monotonic() - started
        now = time.monotonic()
        if pending != last:
            console.print(f"  [dim]{pending:,} stress jobs still to process …[/dim]")
            last = pending
            last_other_report = now
        elif now - last_other_report >= 60:
            # No progress for a minute: say why, so a backlog isn't mistaken for a stall.
            other = other_queued_jobs(conn, provider)
            if other:
                console.print(f"  [dim]… {other:,} other queued jobs are being worked off first[/dim]")
            last_other_report = now
        time.sleep(poll_s)
    return False, time.monotonic() - started


def stress_failure_count(conn, provider: str, with_stored_fingerprint: bool | None = None) -> int:
    """Failed StressJobs.Fail jobs, optionally only those with (or without) a stored fingerprint."""
    cur = conn.cursor()
    try:
        if provider == "sqlserver":
            exists = "EXISTS (SELECT 1 FROM [HangFire].JobParameter p WHERE p.JobId = j.Id AND p.Name = ?)"
            sql = f"SELECT COUNT(*) FROM [HangFire].Job j WHERE j.StateName = 'Failed' AND {_marker_where(provider)}"
        else:
            exists = "EXISTS (SELECT 1 FROM hangfire.jobparameter p WHERE p.jobid = j.id AND p.name = %s)"
            sql = f"SELECT COUNT(*) FROM hangfire.job j WHERE j.statename = 'Failed' AND {_marker_where(provider)}"
        params: tuple = ()
        if with_stored_fingerprint is not None:
            sql += f" AND {'' if with_stored_fingerprint else 'NOT '}{exists}"
            params = (FINGERPRINT_PARAMETER,)
        cur.execute(sql, params)
        return int(cur.fetchone()[0])
    finally:
        cur.close()
        conn.commit()


def top_stored_fingerprint(conn, provider: str) -> tuple[str, int] | None:
    """The stored fingerprint shared by the most StressJobs failures, and how many share it."""
    cur = conn.cursor()
    try:
        if provider == "sqlserver":
            cur.execute(f"""
                SELECT TOP 1 CAST(p.Value AS nvarchar(400)), COUNT(*)
                FROM [HangFire].JobParameter p JOIN [HangFire].Job j ON j.Id = p.JobId
                WHERE p.Name = ? AND j.StateName = 'Failed' AND {_marker_where(provider)}
                GROUP BY CAST(p.Value AS nvarchar(400)) ORDER BY COUNT(*) DESC
            """, (FINGERPRINT_PARAMETER,))
        else:
            cur.execute(f"""
                SELECT p.value, COUNT(*) FROM hangfire.jobparameter p JOIN hangfire.job j ON j.id = p.jobid
                WHERE p.name = %s AND j.statename = 'Failed' AND {_marker_where(provider)}
                GROUP BY p.value ORDER BY COUNT(*) DESC LIMIT 1
            """, (FINGERPRINT_PARAMETER,))
        row = cur.fetchone()
        return (str(row[0]), int(row[1])) if row else None
    finally:
        cur.close()
        conn.commit()


def unstore_fingerprints(conn, provider: str, fraction: float) -> int:
    """Delete the stored FailureFingerprint of about `fraction` of the StressJobs failures."""
    modulo = max(1, int(round(1 / fraction))) if 0 < fraction < 1 else 1
    cur = conn.cursor()
    try:
        if provider == "sqlserver":
            cur.execute(f"""
                DELETE p FROM [HangFire].JobParameter p JOIN [HangFire].Job j ON j.Id = p.JobId
                WHERE p.Name = ? AND j.StateName = 'Failed' AND {_marker_where(provider)} AND j.Id % ? = 0
            """, (FINGERPRINT_PARAMETER, modulo))
        else:
            cur.execute(f"""
                DELETE FROM hangfire.jobparameter p USING hangfire.job j
                WHERE j.id = p.jobid AND p.name = %s AND j.statename = 'Failed' AND {_marker_where(provider)}
                  AND mod(j.id, %s) = 0
            """, (FINGERPRINT_PARAMETER, modulo))
        removed = cur.rowcount
        conn.commit()
        return removed
    finally:
        cur.close()


def purge_stress_jobs(conn, provider: str) -> int:
    """Delete every StressJobs job (states and parameters cascade) and its queue entries."""
    table = _job_table(provider)
    queue_table = "[HangFire].JobQueue" if provider == "sqlserver" else "hangfire.jobqueue"
    id_col, job_col = ("Id", "JobId") if provider == "sqlserver" else ("id", "jobid")
    deleted = 0
    cur = conn.cursor()
    try:
        cur.execute(f"DELETE FROM {queue_table} WHERE {job_col} IN (SELECT {id_col} FROM {table} WHERE {_marker_where(provider)})")
        conn.commit()
        while True:
            if provider == "sqlserver":
                cur.execute(f"DELETE TOP (20000) FROM {table} WHERE {_marker_where(provider)}")
            else:
                cur.execute(f"DELETE FROM {table} WHERE id IN (SELECT id FROM {table} WHERE {_marker_where(provider)} LIMIT 20000)")
            n = cur.rowcount
            conn.commit()
            deleted += max(0, n)
            if n <= 0:
                break
        return deleted
    finally:
        cur.close()


# ─── CLI ──────────────────────────────────────────────────────────────────────

@click.group()
def cli():
    """Set-based seeding for the volume and failure-grouping tiers (StressJobs rows only)."""


@cli.command()
@click.option("--total", "-n", default=100_000, show_default=True, help="Rows to seed across states.")
@click.option("--spread-hours", default=48.0, show_default=True)
@guard.yes_option
def volume(total, spread_hours, assume_yes):
    """Seed Succeeded/Failed/Deleted/Scheduled/Enqueued rows directly."""
    cfg = cfg_mod.load()
    guard.ensure_writable(cfg, f"seed {total:,} jobs", assume_yes)
    conn, provider = get_connection()
    try:
        started = time.monotonic()
        written = seed_volume(conn, provider, total, spread_hours=spread_hours)
        console.print(f"[green]Seeded {sum(written.values()):,} jobs in {time.monotonic() - started:.0f}s:[/green] "
                      + ", ".join(f"{s} {n:,}" for s, n in written.items()))
    finally:
        conn.close()


@cli.command()
@click.option("--count", "-n", default=10_000, show_default=True)
@click.option("--kinds", default=50, show_default=True, help="Distinct kinds of failure (StressJobs.FailureKinds is 50).")
@click.option("--kind", "fixed_kind", type=int, default=None, help="Give every job this one kind (one big group).")
@click.option("--queue", default="default", show_default=True, help="A queue the SampleApp server processes.")
@click.option("--wait/--no-wait", default=True, show_default=True, help="Block until the server has failed them.")
@guard.yes_option
def failures(count, kinds, fixed_kind, queue, wait, assume_yes):
    """Enqueue StressJobs.Fail jobs for the server to fail with real fingerprints."""
    cfg = cfg_mod.load()
    guard.ensure_writable(cfg, f"enqueue {count:,} failing jobs", assume_yes)
    conn, provider = get_connection()
    try:
        enqueue_failures(conn, provider, count, kinds, fixed_kind, queue)
        console.print(f"[green]Enqueued {count:,} failing jobs in '{queue}'.[/green]")
        if wait:
            done, seconds = wait_until_processed(conn, provider)
            colour = "green" if done else "red"
            console.print(f"[{colour}]{'Processed' if done else 'Still pending'} after {seconds:.0f}s; "
                          f"{stress_failure_count(conn, provider):,} stress failures in Failed.[/{colour}]")
    finally:
        conn.close()


@cli.command()
@click.option("--fraction", default=0.5, show_default=True, help="Share of failures to drop the stored fingerprint of (1 = all).")
@guard.yes_option
def unstore(fraction, assume_yes):
    """Delete the stored FailureFingerprint of a share of the stress failures."""
    cfg = cfg_mod.load()
    guard.ensure_writable(cfg, "delete stored failure fingerprints", assume_yes)
    conn, provider = get_connection()
    try:
        removed = unstore_fingerprints(conn, provider, fraction)
        console.print(f"[green]Removed {removed:,} stored fingerprints.[/green]")
    finally:
        conn.close()


@cli.command()
@guard.yes_option
def purge(assume_yes):
    """Delete every StressJobs job seeded by this harness."""
    cfg = cfg_mod.load()
